"""Reusable production authorization checks for durable Runway render jobs."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from app.services.generation_contract import FrozenGenerationContract
from app.services.shot_manifest import recompute_manifest_fingerprint


@dataclass(frozen=True)
class ProductionAuthorizationDecision:
    allowed: bool
    reason: str
    project_id: str
    job_id: str
    actor_id: str = ""


class ProductionAuthorizationError(ValueError):
    def __init__(self, decision: ProductionAuthorizationDecision):
        super().__init__(decision.reason)
        self.decision = decision


def _value(value: Any) -> str:
    return str(getattr(value, "value", value) or "").strip().lower()


def _authoritative_metadata(metadata: Any) -> dict[str, Any] | None:
    if not isinstance(metadata, dict):
        return None
    # This annotation is generated by the adapter after the initial durable
    # check. It is diagnostic only, not part of the frozen production request.
    return {key: value for key, value in metadata.items() if key != "production_authorization"}


def authorize_runway_submission(
    job: Any,
    *,
    storage: Any,
    require_durable: bool = True,
) -> ProductionAuthorizationDecision:
    """Require owner approval, exact storyboard scope, and a frozen Router request.

    ``require_durable=False`` is for the final RenderService creation gate: it
    validates the fully constructed in-memory request before its first durable
    write. Submission and adapter callers keep the default durable-row check.

    The authenticated actor is captured by RenderService when the job is
    created. At the adapter boundary it must still be the persisted project
    owner, and the exact storyboard version and shot frozen into the job must
    remain the currently approved version. Missing evidence denies execution.
    """
    project_id = str(getattr(job, "project_id", "") or "")
    job_id = str(getattr(job, "id", "") or "")
    metadata = getattr(job, "metadata", None)
    metadata = metadata if isinstance(metadata, dict) else {}
    actor_id = str(metadata.get("production_request_actor_id") or "").strip()

    def deny(reason: str) -> ProductionAuthorizationDecision:
        return ProductionAuthorizationDecision(False, reason, project_id, job_id, actor_id)

    if getattr(job, "provider", "") != "runway_router":
        return deny("runway_router_required")
    if storage is None or not project_id or not job_id:
        return deny("durable_production_storage_required")

    try:
        durable = storage.get_job(job_id)
        if require_durable and durable is None:
            return deny("durable_render_job_missing")
        if not require_durable and durable is not None:
            return deny("render_job_id_already_exists")
        if durable is None and not require_durable and not storage.get_project(project_id):
            return deny("project_record_missing")
        if not actor_id:
            return deny("authenticated_production_actor_missing")
        if durable is not None and (
            durable.project_id != project_id
            or durable.shot_id != getattr(job, "shot_id", None)
            or durable.provider != "runway_router"
            or durable.input_payload.model_dump(mode="json") != job.input_payload.model_dump(mode="json")
            or _authoritative_metadata(durable.metadata) != _authoritative_metadata(metadata)
            or durable.metadata.get("production_request_actor_id") != actor_id
        ):
            return deny("durable_render_job_identity_mismatch")
        if (
            getattr(job, "provider", "") != "runway_router"
            or getattr(job, "project_id", "") != project_id
            or not getattr(job, "shot_id", None)
            or not getattr(job, "input_payload", None)
            or not isinstance(job.input_payload.parameters, dict)
        ):
            return deny("durable_render_job_identity_mismatch")
        owner_id = storage.access_project_owner(project_id)
        if not owner_id or owner_id != actor_id:
            return deny("project_owner_mismatch")
        if storage.get_project(project_id) is None:
            return deny("project_record_missing")

        contract_record = metadata.get("creative_generation_contract")
        manifest = metadata.get("creative_generation_manifest")
        identity = metadata.get("creative_generation_identity")
        if not isinstance(contract_record, dict) or not isinstance(manifest, dict) or not isinstance(identity, dict):
            return deny("frozen_generation_identity_missing")
        try:
            contract = FrozenGenerationContract.from_record(contract_record)
            fingerprint = str(metadata.get("creative_manifest_fingerprint") or "")
            if (
                not fingerprint
                or metadata.get("creative_contract_digest") != contract.creative_digest()
                or not isinstance(metadata.get("creative_generation_manifest"), dict)
                or metadata.get("creative_generation_manifest", {}).get("manifest_fingerprint") != fingerprint
                or recompute_manifest_fingerprint(manifest) != fingerprint
                or contract.manifest_fingerprint != fingerprint
                or contract.shot_id != job.shot_id
            ):
                return deny("frozen_generation_contract_integrity_failed")
        except (TypeError, ValueError, KeyError):
            return deny("frozen_generation_contract_integrity_failed")
        if (
            identity.get("job_id") != job_id
            or identity.get("project_id") != project_id
            or identity.get("shot_id") != job.shot_id
            or identity.get("provider") != "runway_router"
        ):
            return deny("frozen_generation_identity_mismatch")
        manifest_scene = manifest.get("scene") if isinstance(manifest.get("scene"), dict) else {}
        storyboard = manifest.get("storyboard") if isinstance(manifest.get("storyboard"), dict) else {}
        scene_id = str(manifest_scene.get("scene_id") or "").strip()
        version_id = str(storyboard.get("storyboard_version") or "").strip()
        entries = [
            row for row in manifest.get("shots", [])
            if isinstance(row, dict) and row.get("shot_id") == job.shot_id
        ] if isinstance(manifest.get("shots"), list) else []
        if not scene_id or not version_id or len(entries) != 1:
            return deny("approved_storyboard_identity_missing")
        storyboard_shot_id = str(entries[0].get("storyboard_shot_id") or "").strip()
        storyboard_parameters = job.input_payload.parameters.get("storyboard")
        if (
            not storyboard_shot_id
            or not isinstance(storyboard_parameters, dict)
            or storyboard_parameters.get("storyboard_shot_id") != storyboard_shot_id
            or storyboard_parameters.get("version_id") != version_id
        ):
            return deny("frozen_storyboard_shot_identity_mismatch")

        blueprint = storage.get_storyboard_blueprint(project_id, scene_id)
        if blueprint is None or blueprint.project_id != project_id or blueprint.scene_id != scene_id:
            return deny("approved_storyboard_missing")
        if (
            blueprint.current_version_id != version_id
            or blueprint.approved_version_id != version_id
            or _value(blueprint.status) not in {"approved", "locked"}
        ):
            return deny("storyboard_approval_stale")
        version = storage.get_storyboard_blueprint_version(version_id)
        if (
            version is None
            or version.version_id != version_id
            or version.blueprint_id != blueprint.blueprint_id
            or version.project_id != project_id
            or version.scene_id != scene_id
            or _value(version.status) not in {"approved", "locked"}
            or not version.approved_at
            or version.approved_by != owner_id
            or not isinstance(version.metadata, dict)
            or version.metadata.get("production_approval") != {
                "actor_id": owner_id,
                "actor_authenticated": True,
            }
        ):
            return deny("storyboard_owner_approval_missing")
        shot = storage.get_storyboard_shot(storyboard_shot_id)
        if (
            shot is None
            or shot.blueprint_id != blueprint.blueprint_id
            or shot.version_id != version_id
            or shot.project_id != project_id
            or shot.scene_id != scene_id
            or shot.shot_id != job.shot_id
            or _value(shot.status) not in {"approved", "locked"}
        ):
            return deny("approved_storyboard_shot_mismatch")
    except ProductionAuthorizationError:
        raise
    except Exception:
        return deny("production_authority_lookup_failed")

    return ProductionAuthorizationDecision(True, "owner_approved_frozen_request", project_id, job_id, actor_id)


def require_runway_submission_authorized(job: Any, *, storage: Any) -> ProductionAuthorizationDecision:
    decision = authorize_runway_submission(job, storage=storage)
    if not decision.allowed:
        raise ProductionAuthorizationError(decision)
    return decision
